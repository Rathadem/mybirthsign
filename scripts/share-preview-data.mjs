// Writes netlify/edge-functions/share-preview-data.js from the site's own data files, so the link-preview
// edge function uses exactly the same animal names, match labels and intro sentences as the website.
// Run after changing js/zodiac-data.js, js/i18n.js or js/compat-text.js:  node scripts/share-preview-data.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
function extractConst(src, name) {
  const start = src.indexOf(`const ${name} =`); if (start < 0) throw new Error(name);
  let i = src.indexOf("=", start) + 1; while (/\s/.test(src[i])) i++;
  const open = src[i], close = open === "{" ? "}" : "]"; let depth = 0, str = null;
  for (let j = i; j < src.length; j++) { const c = src[j];
    if (str) { if (c === "\\") j++; else if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === "`") { str = c; continue; }
    if (c === open) depth++; else if (c === close && --depth === 0) return vm.runInNewContext("(" + src.slice(i, j + 1) + ")"); }
}
const z = read("js/zodiac-data.js"), i18n = read("js/i18n.js"), ct = read("js/compat-text.js");
const INFO = extractConst(z, "ANIMAL_INFO"), TRI = extractConst(z, "ZODIAC_TRIANGLES"), COMPAT = extractConst(z, "COMPAT_INFO");
const KMN = extractConst(i18n, "KM_ANIMAL_NAMES"), KMC = extractConst(i18n, "KM_COMPAT_INFO"), CT = extractConst(ct, "CMP_TEXT");
const data = {
  order: ["Rat", "Ox", "Tiger", "Rabbit", "Dragon", "Snake", "Horse", "Goat", "Monkey", "Rooster", "Dog", "Pig"],
  kmNames: KMN,
  clash: Object.fromEntries(Object.entries(INFO).map(([a, v]) => [a, v.clash])),
  triangles: TRI,
  label: { en: Object.fromEntries(Object.entries(COMPAT).map(([k, v]) => [k, v.label])), km: Object.fromEntries(Object.entries(KMC).map(([k, v]) => [k, v.label])) },
  intro: { en: CT.en.intro, km: CT.km.intro },
};
const out = "// GENERATED by scripts/share-preview-data.mjs from the site's data files. Do not edit by hand.\nexport default " + JSON.stringify(data, null, 1) + ";\n";
fs.writeFileSync(path.join(ROOT, "netlify/edge-functions/share-preview-data.js"), out);
console.log("wrote netlify/edge-functions/share-preview-data.js");
