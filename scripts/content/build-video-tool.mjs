// Builds the browser version of the video prompt pack generator:
//
//   node scripts/content/build-video-tool.mjs
//
// Writes docs/video-prompts/video-pack-tool.html — one self-contained page (works offline, opened from disk, or
// published as a private Claude artifact). It runs the SAME code as the command line:
//   - the pack text from scripts/content/video-pack-lib.mjs,
//   - the day rules copied verbatim from scripts/daily-data-lib.mjs (computeFacts and helpers),
//   - the lucky numbers from js/lucky-digits.js (whole file),
// with the site data (zodiac-data.js / i18n.js) embedded as JSON. Re-run this after changing any of those files.
// Check: node tests/video-tool-test.mjs (compares the page's output with the command line for many dates).
import fs from "node:fs";
import path from "node:path";
import { ROOT, INFO, TRIANGLES, KM_NAMES, KM_INFO, COLOR_HEX } from "../daily-data-lib.mjs";

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const strip = (s) => s.replace(/^export /gm, "");

const libSrc = read("scripts/daily-data-lib.mjs");
const a = libSrc.indexOf("export const ORDER =");
const b = libSrc.indexOf("// ------------------------------------------------------------------ validation");
if (a < 0 || b < 0) throw new Error("daily-data-lib.mjs layout changed: rules block not found");
const rules = strip(libSrc.slice(a, b));

const pick = (o, f) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, f(v)]));
const DATA = {
  INFO: pick(INFO, (v) => ({ luckyNumbers: v.luckyNumbers, luckyColors: v.luckyColors, compatible: v.compatible })),
  TRIANGLES, KM_NAMES,
  KM_INFO: pick(KM_INFO, (v) => ({ luckyColors: v.luckyColors })),
  COLOR_HEX,
};
const code = [
  "/* generated by scripts/content/build-video-tool.mjs — do not edit by hand */",
  `var DATA = ${JSON.stringify(DATA)};`,
  "var INFO = DATA.INFO, TRIANGLES = DATA.TRIANGLES, KM_NAMES = DATA.KM_NAMES, KM_INFO = DATA.KM_INFO, COLOR_HEX = DATA.COLOR_HEX;",
  rules,
  read("js/lucky-digits.js"),
  strip(read("scripts/content/video-pack-lib.mjs")),
].join("\n");

const tpl = read("scripts/content/video-tool-template.html");
if (!tpl.includes("/*__CODE__*/")) throw new Error("template placeholder missing");
const out = path.join(ROOT, "docs", "video-prompts", "video-pack-tool.html");
fs.writeFileSync(out, tpl.replace("/*__CODE__*/", () => code));
console.log("wrote " + path.relative(ROOT, out) + " (" + Math.round(fs.statSync(out).size / 1024) + " KB)");
