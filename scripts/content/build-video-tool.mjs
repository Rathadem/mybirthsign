// Builds the browser version of the video prompt pack generator:
//
//   node scripts/content/build-video-tool.mjs
//
// Writes docs/video-prompts/video-pack-tool.html — one self-contained page (works offline, opened from disk, or
// published as a private Claude artifact). It runs the SAME code as the command line:
//   - the pack text from scripts/content/video-pack-lib.mjs,
//   - the day rules copied verbatim from scripts/daily-data-lib.mjs (computeFacts and helpers),
//   - the lucky numbers from js/lucky-digits.js (whole file),
// with the site data (zodiac-data.js / i18n.js) embedded as JSON. Re-run this after changing any of those files.
// Check: node tests/video-tool-test.mjs (compares the page's output with the command line for many dates).
import fs from "node:fs";
import path from "node:path";
import { ROOT, INFO, TRIANGLES, KM_NAMES, KM_INFO, COLOR_HEX } from "../daily-data-lib.mjs";

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const strip = (s) => s.replace(/^export /gm, "");

const libSrc = read("scripts/daily-data-lib.mjs");
const a = libSrc.indexOf("export const ORDER =");
const b = libSrc.indexOf("// ------------------------------------------------------------------ validation");
if (a < 0 || b < 0) throw new Error("daily-data-lib.mjs layout changed: rules block not found");
const rules = strip(libSrc.slice(a, b));

const pick = (o, f) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, f(v)]));
const DATA = {
  INFO: pick(INFO, (v) => ({ luckyNumbers: v.luckyNumbers, luckyColors: v.luckyColors, compatible: v.compatible, traits: v.traits, weaknesses: v.weaknesses, luckyDays: v.luckyDays })),
  TRIANGLES, KM_NAMES,
  KM_INFO: pick(KM_INFO, (v) => ({ luckyColors: v.luckyColors, traits: v.traits, weaknesses: v.weaknesses, luckyDays: v.luckyDays })),
  COLOR_HEX,
};
// early daily cards (dates whose fortune page is not published yet): the website's own rule-based wording from
// scripts/daily-fortune.mjs (rating labels, "good for" line, trade line) and the Chinese names from js/i18n.js
import vm from "node:vm";
function grabConst(src, name) {
  const start = src.indexOf(`const ${name} =`); if (start < 0) throw new Error(`const ${name} not found`);
  let i = src.indexOf("=", start) + 1; while (/\s/.test(src[i])) i++;
  const open = src[i], close = open === "{" ? "}" : "]"; let depth = 0, str = null;
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    if (str) { if (c === "\\") j++; else if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === "`") { str = c; continue; }
    if (c === open) depth++; else if (c === close && --depth === 0) return vm.runInNewContext("(" + src.slice(i, j + 1) + ")");
  }
  throw new Error(`unterminated const ${name}`);
}
const dfSrc = read("scripts/daily-fortune.mjs"), i18nSrc = read("js/i18n.js"), TT = grabConst(dfSrc, "TRADE_T");
const EARLY = {
  TIER_LABEL: grabConst(dfSrc, "TIER_LABEL"), GOOD_FOR: grabConst(dfSrc, "GOOD_FOR"), TRADE: grabConst(dfSrc, "TRADE"),
  KM_MONTHS: grabConst(dfSrc, "KM_MONTHS"), EN_MONTHS: grabConst(dfSrc, "EN_MONTHS"), ZH_DIR: grabConst(dfSrc, "ZH_DIR"),
  ZH_NAMES: grabConst(i18nSrc, "ZH_ANIMAL_NAMES"), ZH_COLORS: grabConst(i18nSrc, "ZH_COLOR_NAMES"),
  TT: Object.fromEntries(["en", "km", "zh"].map((l) => [l, { h: TT[l].h, best: TT[l].best("{L}") }])),
};
const code = [
  "/* generated by scripts/content/build-video-tool.mjs — do not edit by hand */",
  `var DATA = ${JSON.stringify(DATA)};`,
  `var EARLY = ${JSON.stringify(EARLY)};`,
  "var INFO = DATA.INFO, TRIANGLES = DATA.TRIANGLES, KM_NAMES = DATA.KM_NAMES, KM_INFO = DATA.KM_INFO, COLOR_HEX = DATA.COLOR_HEX;",
  rules,
  read("js/lucky-digits.js"),
  strip(read("scripts/content/video-pack-lib.mjs")),
].join("\n");

const tpl = read("scripts/content/video-tool-template.html");
if (!tpl.includes("/*__CODE__*/")) throw new Error("template placeholder missing");
const out = path.join(ROOT, "docs", "video-prompts", "video-pack-tool.html");
fs.writeFileSync(out, tpl.replace("/*__CODE__*/", () => code));
console.log("wrote " + path.relative(ROOT, out) + " (" + Math.round(fs.statSync(out).size / 1024) + " KB)");
// the same Studio as a page of the site: https://mybirthsign.com/studio/ (not linked, not indexed). There it can read
// the published daily fortune pages and draw the website's share cards; the claude.ai copy cannot reach the site.
// scripts/build-site.mjs copies docs/video-prompts/studio/ to dist/studio/ as it is.
const siteDir = path.join(ROOT, "docs", "video-prompts", "studio");
fs.mkdirSync(siteDir, { recursive: true });
fs.writeFileSync(path.join(siteDir, "index.html"), '<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="robots" content="noindex,nofollow">' +
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Sans+Khmer:wght@400;700&family=Noto+Sans+SC:wght@400;700&display=swap">' +
  "<style>@font-face{font-family:'Moul';src:url(/css/fonts/moul-khmer-400.woff2) format('woff2');font-display:swap}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style></head><body>\n" + fs.readFileSync(out, "utf8") + "\n</body></html>\n");
console.log("wrote docs/video-prompts/studio/index.html (site copy, /studio/)");
